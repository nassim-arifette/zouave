import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import { homedir } from 'node:os';
import assert from 'node:assert/strict';
const shots = `${homedir()}/zouave-notes/shots`;
await mkdir(shots, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? `${homedir()}/.local/bin/google-chrome`, headless: true, args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error') console.log('BROWSER:', msg.text()); });
  await page.goto(process.env.ZOUAVE_URL ?? 'http://127.0.0.1:3000', { waitUntil: 'networkidle' });
  await page.locator('#level-value').filter({ hasText: /m/ }).waitFor();
  await page.waitForTimeout(3000);
  await page.screenshot({ path: `${shots}/01-initial-3d.png` });
  await page.getByRole('button', { name: /Montre-moi 1910/ }).click();
  await page.locator('#scenario-card').waitFor({ state: 'visible' });
  await page.waitForTimeout(4500);
  await page.screenshot({ path: `${shots}/02-1910-water.png` });
  await page.getByRole('button', { name: /Et chez moi/ }).click();
  await page.locator('#exposure-card').waitFor({ state: 'visible' });
  await page.waitForTimeout(3500);
  if (await page.locator('#photo-dialog').isVisible()) await page.getByRole('button', { name: 'Fermer la photo' }).click();
  assert.match(await page.locator('#exposure-card').innerText(), /1 à 2 m/);
  assert.match(await page.locator('#exposure-card').innerText(), /Traversière/);
  assert.match(await page.locator('#exposure-card').innerText(), /Secteur exposé/);
  await page.screenshot({ path: `${shots}/03-home-exposure.png` });
  await page.getByRole('button', { name: /Qu’est-ce que je fais/ }).click();
  await page.locator('#safety-card').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#safety-card li').count(), 3);
  await page.screenshot({ path: `${shots}/04-safety.png` });
  await page.locator('#safety-card .card-close').click();
  await page.getByRole('button', { name: /Pire que 1910/ }).click();
  await page.locator('#exposure-card').filter({ hasText: 'Emprise seulement' }).waitFor();
  assert.match(await page.locator('#exposure-card').innerText(), /Emprise seulement/);
  await page.screenshot({ path: `${shots}/05-extreme.png` });
  await page.getByRole('button', { name: /Aujourd’hui/ }).click();
  await page.locator('#exposure-card').filter({ hasText: 'Aucune simulation' }).waitFor();
  assert.match(await page.locator('#exposure-card').innerText(), /Aucune simulation/);
  const input = page.locator('#chat');
  await input.fill('adresse introuvable qqq'); await input.press('Enter');
  await page.waitForFunction(() => !document.querySelector('#caption').textContent.includes('Je consulte'));
  assert.match(await page.locator('#caption').innerText(), /introuvable|indisponible/);
  assert.deepEqual(errors, []);
  console.log('PASS browser: initial 3D, animated 1910, demo exposure 1–2 m + caves, three safety instructions, extreme footprint, today reset, unknown address error.');
  console.log(`Screenshots: ${shots}/01-initial-3d.png … 05-extreme.png`);
} finally { await browser.close(); }
